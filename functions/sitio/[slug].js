// GET /sitio/:slug — pagina del negocio.
// Si hay datos estructurados (sitio-data:) con productos, renderiza la TIENDA
// (carrito + checkout estilo Amazon). Si no, sirve el HTML estatico anterior.
export async function onRequestGet(context) {
  const slug = context.params.slug;
  if (!slug || !/^[a-z0-9-]{1,40}$/.test(slug)) {
    return new Response('Sitio no encontrado', { status: 404 });
  }
  try {
    const dataJson = await context.env.SITIOS.get("sitio-data:" + slug);
    if (dataJson) {
      const data = JSON.parse(dataJson);
      if (data && Array.isArray(data.products) && data.products.length > 0) {
        return new Response(renderStore(slug, data), {
          headers: { 'Content-Type': 'text/html; charset=utf-8' },
        });
      }
    }
  } catch (e) { /* usar HTML estatico */ }
  const html = await context.env.SITIOS.get("sitio:" + slug);
  if (!html) {
    return new Response('Sitio no encontrado', { status: 404 });
  }
  return new Response(html, { headers: { 'Content-Type': 'text/html; charset=utf-8' } });
}

function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;')
    .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

